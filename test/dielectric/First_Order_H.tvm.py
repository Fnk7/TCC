@auto_scheduler.register_workload
def first_order_h(s0, s1):
    t2 = te.placeholder((s0, 3,), dtype="float64", name="t2")
    t3 = te.placeholder((s0, 3,), dtype="float64", name="t3")
    t4 = te.placeholder((s0,), dtype="float64", name="t4")
    t5 = te.placeholder((s0,), dtype="float64", name="t5")
    t6 = te.placeholder((s0,), dtype="float64", name="t6")
    t7 = te.placeholder((s0,), dtype="float64", name="t7")
    t8 = te.placeholder((s0,), dtype="float64", name="t8")
    t9 = te.placeholder((s0,), dtype="float64", name="t9")
    t10 = te.placeholder((s0,), dtype="float64", name="t10")
    t11 = te.placeholder((s0, s1,), dtype="float64", name="t11")
    t12 = te.placeholder((s0, 3, s1,), dtype="float64", name="t12")
    cst0 = 0.5
    var0 = te.compute((s0,), lambda *ls: cst0 * t5[ls[0]], name="var0")
    var1 = te.compute((s0,), lambda *ls: t6[ls[0]] * t7[ls[0]], name="var1")
    var2 = te.compute((s0,), lambda *ls: cst0 * var1[ls[0]], name="var2")
    var3 = te.compute((s0, 3,), lambda *ls: t2[ls[0]][ls[1]] * t3[ls[0]][ls[1]], name="var3")
    a0 = te.reduce_axis((0, 3), name="a0")
    var4 = te.compute((s0,), lambda *ls: te.sum(var3[ls[0]][a0], axis=a0), name="var4")
    var5 = te.compute((s0,), lambda *ls: t8[ls[0]] * var4[ls[0]], name="var5")
    var6 = te.compute((s0,), lambda *ls: cst0 * var5[ls[0]], name="var6")
    var7 = te.compute((s0,), lambda *ls: var0[ls[0]] + var2[ls[0]] + var6[ls[0]], name="var7")
    var8 = te.compute((s0,), lambda *ls: t4[ls[0]] * var7[ls[0]], name="var8")
    var9 = te.compute((s0, s1,), lambda *ls: t11[ls[0]][ls[1]] * var8[ls[0]], name="var9")
    var10 = te.compute((s0,), lambda *ls: t7[ls[0]] * t8[ls[0]], name="var10")
    var11 = te.compute((s0,), lambda *ls: t9[ls[0]] * var4[ls[0]], name="var11")
    var12 = te.compute((s0,), lambda *ls: var10[ls[0]] + var11[ls[0]], name="var12")
    var13 = te.compute((s0,), lambda *ls: t4[ls[0]] * t10[ls[0]], name="var13")
    var14 = te.compute((s0, 3,), lambda *ls: t3[ls[0]][ls[1]] * var13[ls[0]], name="var14")
    var15 = te.compute((s0,), lambda *ls: t4[ls[0]] * var12[ls[0]], name="var15")
    var16 = te.compute((s0, 3,), lambda *ls: t2[ls[0]][ls[1]] * var15[ls[0]], name="var16")
    var17 = te.compute((s0, 3,), lambda *ls: var14[ls[0]][ls[1]] + var16[ls[0]][ls[1]], name="var17")
    var18 = te.compute((s0, 3, s1,), lambda *ls: var17[ls[0]][ls[1]] * t12[ls[0]][ls[1]][ls[2]], name="var18")
    a1 = te.reduce_axis((0, 3), name="a1")
    var19 = te.compute((s0, s1,), lambda *ls: te.sum(var18[ls[0]][a1][ls[1]], axis=a1), name="var19")
    var20 = te.compute((s0, s1,), lambda *ls: var9[ls[0]][ls[1]] + var19[ls[0]][ls[1]], name="var20")
    var21 = te.compute((s0, s1, s1,), lambda *ls: t11[ls[0]][ls[1]] * var20[ls[0]][ls[2]], name="var21")
    a2 = te.reduce_axis((0, s0), name="a2")
    var22 = te.compute((s1, s1,), lambda *ls: te.sum(var21[a2][ls[0]][ls[1]], axis=a2), name="var22")
    var23 = te.compute((s1, s1,), lambda *ls: var22[ls[0]][ls[1]] + var22[ls[1]][ls[0]], name="var23")
    return [t2, t3, t4, t5, t6, t7, t8, t9, t10, t11, t12, var23]
